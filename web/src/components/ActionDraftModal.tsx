import React, { useState, useEffect } from 'react';
import {
  X,
  Mail,
  FileSpreadsheet,
  ListOrdered,
  Copy,
  Check,
  AlertTriangle,
  ShieldCheck,
  Sparkles,
  Loader2,
} from 'lucide-react';
import { api } from '../api';
import type { ActionDraft, Move } from '../types';

interface ActionDraftModalProps {
  move: Move | null;
  isOpen: boolean;
  onClose: () => void;
  onApproveMove?: (moveId: string) => void;
}

export const ActionDraftModal: React.FC<ActionDraftModalProps> = ({
  move,
  isOpen,
  onClose,
  onApproveMove,
}) => {
  const [draft, setDraft] = useState<ActionDraft | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (isOpen && move) {
      setLoading(true);
      setError(null);
      setCopied(false);
      api
        .draftMove(move.id)
        .then((res) => setDraft(res))
        .catch((err) => setError(err.message || 'Failed to generate draft'))
        .finally(() => setLoading(false));
    } else {
      setDraft(null);
    }
  }, [isOpen, move]);

  if (!isOpen || !move) return null;

  const handleCopy = () => {
    if (!draft) return;
    const textToCopy = draft.subject
      ? `Subject: ${draft.subject}\n\n${draft.body}`
      : draft.body;
    navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const getKindBadge = (kind: ActionDraft['kind']) => {
    switch (kind) {
      case 'email':
        return (
          <span className="badge-indigo font-mono">
            <Mail className="w-3.5 h-3.5 mr-1" />
            EMAIL DRAFT
          </span>
        );
      case 'invoice_lines':
        return (
          <span className="badge-emerald font-mono">
            <FileSpreadsheet className="w-3.5 h-3.5 mr-1" />
            INVOICE SPECIFICATION
          </span>
        );
      case 'steps':
        return (
          <span className="badge-amber font-mono">
            <ListOrdered className="w-3.5 h-3.5 mr-1" />
            OPERATIONAL STEPS
          </span>
        );
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
      {/* Backdrop */}
      <div
        className="absolute inset-0 bg-black/80 backdrop-blur-md transition-opacity"
        onClick={onClose}
      />

      <div className="relative w-full max-w-2xl bg-slate-900 border border-slate-700/80 rounded-3xl shadow-2xl overflow-hidden z-10 animate-fade-in flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="p-6 border-b border-slate-800 flex items-start justify-between bg-slate-925/90">
          <div className="space-y-1">
            <div className="flex items-center gap-2">
              <span className="badge-emerald font-mono text-[10px]">
                RANK #{move.rank}
              </span>
              {draft && getKindBadge(draft.kind)}
              <span className="text-xs text-slate-400 font-mono">
                ID: {move.id}
              </span>
            </div>
            <h3 className="text-lg font-bold text-white tracking-tight">
              Action Draft: {move.title}
            </h3>
            <p className="text-xs text-slate-400">
              Generated by Drafter Agent • Grounded in Zetaris SQL Evidence
            </p>
          </div>

          <button
            onClick={onClose}
            className="p-2 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors cursor-pointer"
            aria-label="Close modal"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Safety Disclaimer Banner */}
        <div className="px-6 py-3 bg-amber-500/10 border-b border-amber-500/20 flex items-center justify-between gap-3 text-xs text-amber-300">
          <div className="flex items-center gap-2">
            <AlertTriangle className="w-4 h-4 text-amber-400 shrink-0" />
            <span className="font-semibold">
              Never sent automatically:
            </span>
            <span className="text-amber-200/90">
              Human-in-the-Loop review required before dispatching or modifying invoices.
            </span>
          </div>
          <span className="hidden sm:inline-flex items-center gap-1 font-mono text-[11px] text-amber-400/80 bg-amber-950/60 px-2 py-0.5 rounded border border-amber-500/30 shrink-0">
            <ShieldCheck className="w-3 h-3" />
            Zero Autonomous Send
          </span>
        </div>

        {/* Modal Body */}
        <div className="p-6 overflow-y-auto space-y-5 flex-1">
          {loading && (
            <div className="py-16 text-center space-y-3">
              <Loader2 className="w-8 h-8 text-emerald-400 animate-spin mx-auto" />
              <p className="text-xs font-mono text-slate-400">
                Synthesizing draft from verified evidence rows...
              </p>
            </div>
          )}

          {error && (
            <div className="p-4 rounded-xl bg-rose-950/40 border border-rose-500/40 text-rose-300 text-xs">
              {error}
            </div>
          )}

          {draft && !loading && (
            <>
              {/* Subject Line (if email/invoice) */}
              {draft.subject && (
                <div className="p-3.5 rounded-xl bg-slate-950/80 border border-slate-800 space-y-1">
                  <span className="text-[10px] font-mono uppercase tracking-wider text-slate-400 font-semibold block">
                    Subject Line
                  </span>
                  <div className="text-sm font-medium text-slate-200 font-mono select-all">
                    {draft.subject}
                  </div>
                </div>
              )}

              {/* Ungrounded warning (if critic flagged numbers) */}
              {draft.ungrounded && draft.ungrounded.length > 0 && (
                <div className="p-3 rounded-xl bg-rose-950/30 border border-rose-500/30 text-xs text-rose-300 flex items-center gap-2">
                  <AlertTriangle className="w-4 h-4 text-rose-400 shrink-0" />
                  <span>
                    Critic Notice: Flagged ungrounded amount ({draft.ungrounded.join(', ')}). Revised to fallback template.
                  </span>
                </div>
              )}

              {/* Content Body Preview */}
              <div className="space-y-1.5">
                <div className="flex items-center justify-between text-xs text-slate-400">
                  <span className="font-mono uppercase tracking-wider text-[11px] font-semibold">
                    Draft Content ({draft.kind})
                  </span>
                  <span className="font-mono text-[11px] text-emerald-400 flex items-center gap-1">
                    <ShieldCheck className="w-3.5 h-3.5" />
                    100% Grounded in Evidence
                  </span>
                </div>

                <div className="p-4 rounded-2xl bg-slate-950 border border-slate-800 text-slate-200 font-mono text-xs sm:text-sm leading-relaxed whitespace-pre-wrap select-all shadow-inner">
                  {draft.body}
                </div>
              </div>

              {/* Underlying Move Rationale */}
              <div className="p-3.5 rounded-xl bg-slate-950/40 border border-slate-800/60 text-xs text-slate-400 flex items-start gap-2.5">
                <Sparkles className="w-4 h-4 text-emerald-400 shrink-0 mt-0.5" />
                <div>
                  <span className="font-semibold text-slate-300">CFO Rationale: </span>
                  {move.reason}
                </div>
              </div>
            </>
          )}
        </div>

        {/* Footer */}
        <div className="p-5 border-t border-slate-800 bg-slate-925/90 flex flex-wrap items-center justify-between gap-3">
          <div className="text-xs text-slate-400 font-mono">
            {move.monthly_impact_eur > 0
              ? `Impact: +€${move.monthly_impact_eur.toFixed(2)}/mo`
              : 'Overdue recovery action'}
          </div>

          <div className="flex items-center gap-2.5">
            <button
              onClick={handleCopy}
              disabled={loading || !draft}
              className={`px-4 py-2 rounded-xl text-xs font-semibold flex items-center gap-1.5 transition-all cursor-pointer border ${
                copied
                  ? 'bg-emerald-500/20 border-emerald-500/40 text-emerald-300'
                  : 'bg-slate-800 hover:bg-slate-750 border-slate-700 text-slate-200'
              }`}
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-400" />
                  <span>Copied to Clipboard!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Text</span>
                </>
              )}
            </button>

            {onApproveMove && move.status !== 'approved' && (
              <button
                onClick={() => {
                  onApproveMove(move.id);
                  onClose();
                }}
                className="px-4 py-2 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold shadow-glow-emerald transition-all flex items-center gap-1.5 cursor-pointer active:scale-[0.98]"
              >
                <Sparkles className="w-3.5 h-3.5" />
                <span>Approve Move</span>
              </button>
            )}

            <button
              onClick={onClose}
              className="px-3.5 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-medium transition-colors cursor-pointer"
            >
              Close
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
